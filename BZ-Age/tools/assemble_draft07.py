#!/usr/bin/env python3
"""Build the draft-07 narration file and visual-cue sheet from the part files.

Run from the BZ-Age/ folder:  python3 tools/assemble_draft07.py
Reads each part's draft-07 file, takes the text between "## The Draft" and
"## Revision notes", drops "---" rules, and separates the [VISUAL: ...] lines.
Also refreshes the "Narration length" line in each part's header.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PARTS = [
    ("Prologue", "02-Parts/Part-00-Prologue/cold-open-draft-07.md"),
    ("Part 1", "02-Parts/Part-1-Before-Bronze/draft-07.md"),
    ("Part 2", "02-Parts/Part-2-First-Cities/draft-07.md"),
    ("Part 3", "02-Parts/Part-3-First-Empires/draft-07.md"),
    ("Part 4", "02-Parts/Part-4-Middle-Bronze/draft-07.md"),
    ("Part 5", "02-Parts/Part-5-Cosmopolitan-Age/draft-07.md"),
    ("Part 6", "02-Parts/Part-6-Crisis-Builds/draft-07.md"),
    ("Part 7", "02-Parts/Part-7-Collapse/draft-07.md"),
    ("Part 8", "02-Parts/Part-8-Long-Aftermath/draft-07.md"),
    ("Part 9", "02-Parts/Part-9-Inheritance-Memory/draft-07.md"),
]
WPM = 150

narration, cues, table, total = [], [], [], 0
for label, rel in PARTS:
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
    title = text.splitlines()[0].lstrip("# ").strip()
    body = text.split("## The Draft", 1)[1].split("## Revision notes", 1)[0]
    lines, part_cues, spoken = [], [], []
    for line in body.splitlines():
        s = line.strip()
        if s == "---":
            continue
        if s.startswith("[VISUAL:"):
            words_so_far = sum(len(x.split()) for x in spoken)
            mins = words_so_far / WPM
            stamp = f"{int(mins):02d}:{int((mins % 1) * 60):02d}"
            part_cues.append(f"- **~{stamp}** {s[len('[VISUAL:'):].rstrip(']').strip()}")
            continue
        lines.append(line)
        if s:
            spoken.append(s)
    words = sum(len(x.split()) for x in spoken)
    total += words
    clean = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()
    narration.append(f"# {title}\n\n{clean}\n")
    cues.append(f"## {title}\n\n" + "\n".join(part_cues) + "\n")
    table.append((title, words, round(words / WPM)))
    # refresh header length line
    head, rest = text.split("\n---\n", 1)
    head = "\n".join(l for l in head.splitlines()
                     if not l.startswith("**Estimated audio length:**")
                     and not l.startswith("**Narration length:**"))
    head += f"\n**Narration length:** {words:,} words (about {round(words / WPM)} minutes at {WPM} words a minute)"
    path.write_text(head + "\n\n---\n" + rest.lstrip("\n") if not rest.startswith("\n") else head + "\n\n---\n" + rest, encoding="utf-8")

hours = total / WPM / 60
summary = "| Part | Words | Minutes |\n|---|---|---|\n" + "\n".join(
    f"| {t} | {w:,} | {m} |" for t, w, m in table) + f"\n| **Total** | **{total:,}** | **{round(total / WPM)}** (about {hours:.1f} hours) |\n"

(ROOT / "BZ-Age-draft07-audiobook.md").write_text(
    "# BZ-Age — Draft-07 Narration (v0.7.3)\n\n"
    "*Built by `tools/assemble_draft07.py` from the draft-07 part files. Narration only: "
    "visual cues and revision notes are removed. Do not edit this file; edit the part files and rebuild.*\n\n"
    + "\n\n".join(narration), encoding="utf-8")
(ROOT / "BZ-Age-draft07-visual-cues.md").write_text(
    "# BZ-Age — Draft-07 Visual Cue Sheet (v0.7.3)\n\n"
    "*Built by `tools/assemble_draft07.py`. Times are estimates from word position at "
    f"{WPM} words a minute, measured from the start of each part. Four kinds of cue: part card, map, object, diagram.*\n\n"
    + summary + "\n" + "\n".join(cues), encoding="utf-8")
print(summary)
